// Движок правил: чистый Kotlin/JVM (архитектура §6.1).
//
// Здесь СОЗНАТЕЛЬНО нет ни Android SDK, ни Room, ни сетевых библиотек, ни libphonenumber.
// Это не аккуратность, а техническая гарантия двух требований ТЗ:
//   * «проверка звонка не делает сетевых запросов» (ТЗ §10) — сети нет в classpath;
//   * движок переносим на iOS и тестируется на JVM (ТЗ §8.5, §17).
// Нормализация номера объявляется здесь интерфейсом, а реализуется в :core — стоимость
// загрузки метаданных региона не укладывается в бюджет звонка, а Android-порт требует Context
// (архитектура §6.3).
//
// Список зависимостей проверяется задачей verifyModuleBoundaries в :core.

plugins {
    id("org.jetbrains.kotlin.jvm")

    // JaCoCo — штатный плагин Gradle, а не внешняя зависимость: агент и утилита отчёта живут
    // в отдельных конфигурациях (`jacocoAgent`, `jacocoAnt`) и в compile/runtime classpath
    // движка не попадают. Правило «в :engine никаких зависимостей» этим не нарушается.
    // Альтернативы отклонены: Kover тянет плагин из внешнего репозитория и завязан на версию
    // Kotlin, а «мерить покрытие глазами по отчёту тестов» не роняет сборку, то есть не является
    // проверкой вовсе.
    jacoco
}

kotlin {
    jvmToolchain(17)
    explicitApi()
}

jacoco {
    // Версия агента зафиксирована сознательно: порог покрытия — критерий приёмки, и его
    // выполнение не должно меняться само по себе при обновлении Gradle. Агент обязан понимать
    // байткод, который порождает Kotlin 2.2 под JVM 17.
    toolVersion = "0.8.13"
}

dependencies {
    testImplementation(kotlin("test"))
}

tasks.test {
    useJUnitPlatform()
    testLogging {
        events("failed", "skipped")
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
    }
}

// --- замер покрытия и порог, проверяемый сборкой (ТЗ §18 п.28) -----------------------------
//
// Порог записан здесь один раз и больше нигде: CI вызывает задачу, а не повторяет число.
// Значение — из критерия приёмки ТЗ §18 п.28: «покрытие модуля engine ≥ 85 %».
// Понижать его нельзя: критерий приёмки правится в ТЗ, а не в файле сборки.
// (`toBigDecimal()`, а не `java.math.BigDecimal(...)`: в build-скрипте имя `java` занято
// расширением JavaPluginExtension, и до пакета java.math по нему не добраться.)
val coverageMinimum = "0.85".toBigDecimal()

// Счётчик — INSTRUCTION, а не LINE. Причина в Kotlin: LINE считает строку покрытой, если
// выполнилась хотя бы одна инструкция на ней, а Kotlin размещает на одной строке выражение
// целиком (`?:`, однострочные ветки `when`, expression body). При таком счётчике непройденная
// ветка elvis-оператора считается покрытой, и 85 % по строкам оказываются слабее, чем выглядят.
// BRANCH отклонён: он требует проходить сгенерированные проверки на null в публичных функциях,
// куда из Kotlin недостижимо, — порог упирался бы в байткод, а не в тесты.
val coverageCounter = "INSTRUCTION"

tasks.jacocoTestReport {
    // Отчёт строится по свежим данным: без этой зависимости задача молча использует
    // .exec от прошлого прогона, а на чистой машине падает на его отсутствии.
    dependsOn(tasks.test)
    reports {
        xml.required = true // для внешних инструментов и диффа покрытия между сборками
        html.required = true // чтобы в артефактах CI было видно, каких классов не хватает
    }
}

tasks.jacocoTestCoverageVerification {
    dependsOn(tasks.test)
    violationRules {
        rule {
            element = "BUNDLE" // порог по модулю целиком, как и сформулировано в ТЗ
            limit {
                counter = coverageCounter
                value = "COVEREDRATIO"
                minimum = coverageMinimum
            }
        }
    }
}

// Порог входит в `check`: иначе он проверялся бы только тем, кто помнит про отдельную задачу.
tasks.named("check") { dependsOn(tasks.jacocoTestCoverageVerification) }
