package com.mist3s.nopecall.core.contacts

import com.mist3s.nopecall.engine.NumberForms

/**
 * Номера телефонной книги для предпросмотра правила (ТЗ §9.3, критерий приёмки §18 п. 16).
 *
 * **Почему не через [ContactIndex].** Индекс хранит только усечённые хеши номеров, и по хешу
 * отвечается ровно один вопрос — «этот номер есть в книге». Хеш не сохраняет ни порядок цифр,
 * ни длину, поэтому проверить по нему «начинается с 7495» невозможно в принципе: пришлось бы
 * перебрать все номера, дающие такой префикс, то есть миллиарды строк. Предпросмотру нужны
 * сами номера — значит нужен разовый проход по книге.
 *
 * **Почему проход допустим.** Предпросмотр — это интерфейс, а не горячий путь. Обращение
 * к `ContentProvider` запрещено из `onScreenCall`, где синхронный запрос нельзя прервать
 * по таймауту (архитектура §5.3); в редакторе правила таймаута нет, а пользователь этой
 * операции ждёт и видит её результат.
 *
 * **Номера не сохраняются нигде.** Ни в Room, ни в файл, ни в снимок: они живут только внутри
 * вызова [numbers]. Иначе адресная книга появилась бы во втором месте, и её пришлось бы
 * защищать, версионировать и чистить наравне с журналом — ради подсказки в редакторе.
 *
 * Интерфейс, а не прямой `ContentResolver`, по той же причине, что и
 * [com.mist3s.nopecall.core.calllog.CallLogSource]: иначе показатель «правило зацепит N ваших
 * контактов» нельзя проверить без устройства, а ошибка в нём — это ложное «своих не тронет».
 */
public interface ContactNumberSource {

    /**
     * Номера книги без повторов, в разобранном виде.
     *
     * Возвращаются [NumberForms], а не строки: сопоставление с шаблоном должно идти по всем
     * видам номера, как это делает движок (`8495…`, `+7495…`, `9991234567`), и повторять здесь
     * разбор номера означало бы завести вторую реализацию нормализации.
     *
     * Один метод, а не `isAvailable()` плюс чтение: между двумя вызовами разрешение можно
     * отозвать, и тогда «доступ есть, номеров ноль» превратило бы «не смогли проверить»
     * в утверждение «ни один контакт не пострадает» (ТЗ §1.1).
     *
     * @param limit сколько номеров прочитать максимум. Достигнутый предел — это нижняя
     *   граница показателя, и вызывающий обязан сказать об этом «≥ N», а не выдать за точное.
     * @return номера книги, либо `null` если разрешения `READ_CONTACTS` нет или книгу
     *   не удалось прочитать. `null` — это «не знаю», а не «пусто».
     */
    public fun numbers(limit: Int): List<NumberForms>?

    public companion object {
        /**
         * Источника нет: разрешение не выдано или предпросмотр вызван оттуда, где `Context`
         * недоступен. Значение по умолчанию — именно «не знаю», а не пустой список: пустой
         * список тут же стал бы показателем «0 контактов».
         */
        public val UNAVAILABLE: ContactNumberSource = object : ContactNumberSource {
            override fun numbers(limit: Int): List<NumberForms>? = null
        }
    }
}
