package com.mist3s.nopecall.updater

import java.io.File

/**
 * Передача проверенного APK системному установщику (ТЗ §15.5).
 *
 * Интерфейс, потому что `PackageInstaller` на голой JVM недоступен, а проверить нужно главное:
 * при несовпадении суммы или отпечатка установщик **не зовётся вообще**. Тест с поддельной
 * реализацией это и утверждает.
 *
 * Реализация — [SystemApkInstaller].
 */
public interface ApkInstaller {

    /**
     * @param apk файл, уже прошедший проверку суммы и отпечатка. Реализация ничего не проверяет:
     *   проверки живут в одном месте ([UpdateManager]), иначе появилась бы вторая, расходящаяся
     *   с первой, и вопрос «проверили ли этот файл» не имел бы однозначного ответа.
     */
    public fun install(apk: File): InstallResult
}
