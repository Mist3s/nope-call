package com.mist3s.nopecall.updater

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNull
import kotlin.test.assertTrue

/**
 * Сравнение версий (ТЗ §15.2, §15.5).
 *
 * Именно эта функция решает, предлагать обновление. Тесты ниже фиксируют случаи, в которых
 * «наивное» сравнение строк или чисел даёт неверный ответ.
 */
class SemVerTest {

    private fun v(text: String): SemVer =
        SemVer.parseOrNull(text) ?: error("версия \"$text\" должна разбираться")

    @Test
    fun `1_10_0 новее 1_9_9`() {
        // Ловит сравнение версий как строк: "1.10.0" < "1.9.9" лексикографически, то есть
        // после 1.9.9 приложение никогда бы не предложило 1.10.0.
        assertTrue(v("1.10.0") > v("1.9.9"), "1.10.0 обязана быть новее 1.9.9")
        assertTrue(v("1.9.9") < v("1.10.0"), "сравнение обязано быть симметричным")
    }

    @Test
    fun `релиз новее своего предвыпуска`() {
        // Ловит забытое правило semver 11.3: у 1.2.3 и 1.2.3-rc1 совпадает числовая часть,
        // и без отдельной проверки они сравнивались бы как равные — то есть после rc1
        // релиз 1.2.3 не предлагался бы вовсе.
        assertTrue(v("1.2.3") > v("1.2.3-rc1"), "1.2.3 обязана быть новее 1.2.3-rc1")
    }

    @Test
    fun `предвыпуски сравниваются между собой`() {
        assertTrue(v("1.2.3-rc2") > v("1.2.3-rc1"), "rc2 обязан быть новее rc1")
        assertTrue(v("1.2.3-rc1") > v("1.2.2"), "предвыпуск новее предыдущего релиза")
    }

    @Test
    fun `числовые идентификаторы предвыпуска сравниваются как числа`() {
        // Ловит сравнение идентификаторов строками: "10" < "2" лексикографически.
        // Правило semver 11.4.1 требует числового сравнения там, где идентификатор — число.
        assertTrue(v("1.2.3-rc.10") > v("1.2.3-rc.2"), "rc.10 обязан быть новее rc.2")
        // Тот же случай без точки числовым НЕ является — это документированное свойство semver,
        // из-за которого теги предвыпусков после девятого должны выглядеть как -rc.10.
        assertTrue(v("1.2.3-rc10") < v("1.2.3-rc2"), "rc10 без точки сравнивается как строка")
    }

    @Test
    fun `более длинный предвыпуск новее при одинаковом начале`() {
        // Правило semver 11.4.4. Ловит сравнение только по общей части списка.
        assertTrue(v("1.2.3-rc.1.2") > v("1.2.3-rc.1"), "длинный идентификатор новее короткого")
    }

    @Test
    fun `числовой идентификатор младше буквенного`() {
        // Правило semver 11.4.3: 1.2.3-1 младше 1.2.3-alpha.
        assertTrue(v("1.2.3-1") < v("1.2.3-alpha"), "число младше буквенно-цифрового")
    }

    @Test
    fun `имя тега с v и метаданные сборки не мешают`() {
        // Ловит сравнение имени тега «как есть»: релизы называются v1.2.3, а в манифесте
        // версия записана без v — без нормализации обновление не нашлось бы ни разу.
        assertEquals(v("1.2.3"), v("v1.2.3"), "ведущая v обязана отбрасываться")
        // Метаданные сборки в сравнении не участвуют по стандарту (semver 10).
        assertEquals(v("1.2.3"), v("1.2.3+ci.45"), "метаданные сборки не влияют на порядок")
    }

    @Test
    fun `мусор вместо версии не разбирается`() {
        // Возврат null, а не исключение и не «нулевая версия»: неразобранная версия обязана
        // приводить к отказу от обновления, а 0.0.0 сделала бы любой релиз «новее».
        assertNull(SemVer.parseOrNull(null), "null не версия")
        assertNull(SemVer.parseOrNull(""), "пустая строка не версия")
        assertNull(SemVer.parseOrNull("1.2"), "версия без patch не разбирается")
        assertNull(SemVer.parseOrNull("1.2.3.4"), "четыре части — не semver")
        assertNull(SemVer.parseOrNull("latest"), "имя тега без версии не разбирается")
        assertNull(SemVer.parseOrNull("1.2.x"), "нецифровая часть не разбирается")
        assertNull(SemVer.parseOrNull("1.2.3-"), "пустой предвыпуск не разбирается")
        assertNull(SemVer.parseOrNull("1.2.3-rc 1"), "пробел не допускается в идентификаторе")
    }

    @Test
    fun `признак предвыпуска виден снаружи`() {
        // Нужен фильтру «предварительные версии»: без него галочка ничего не значила бы.
        assertTrue(v("1.2.3-rc1").isPrerelease, "1.2.3-rc1 — предвыпуск")
        assertFalse(v("1.2.3").isPrerelease, "1.2.3 — обычный релиз")
    }
}
