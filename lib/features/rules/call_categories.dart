/// Разбор поля правила: категории перечисляются через запятую (как и в движке).
List<String> parseCategories(String pattern) =>
    pattern.split(',').map((e) => e.trim()).where((e) => e.isNotEmpty).toList();

/// Сборка поля из выбранных категорий. Порядок сохраняется: пользователь его видит.
String joinCategories(Iterable<String> categories) => categories.join(', ');
