/// Категории, наблюдённые на реальных звонках, но отсутствующие в перечне.
///
/// Держатся отдельным списком и **не смешиваются** с официальным: перечень — это то, что
/// предписано, а это — то, что приходит фактически. Смешать их значило бы выдать наблюдение
